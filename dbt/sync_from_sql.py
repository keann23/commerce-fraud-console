"""Generate the dbt project's models from the plain SQL in sql/, so there is one source of truth.

sql/ stays canonical (it is what `make detect` and the app run). This script turns every
`CREATE OR REPLACE TABLE|VIEW name AS <select>` into models/<layer>/<name>.sql, swapping
table names for {{ ref() }} (other models) and {{ source() }} (raw warehouse tables), and copies
sql/macros.sql into a dbt macro that runs before each dbt invocation.

  python dbt/sync_from_sql.py          write the models
  python dbt/sync_from_sql.py --check  exit 1 if the models are stale (used by tests)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SQL = ROOT / "sql"
DBT = ROOT / "dbt"
STAGES = [("features", sorted((SQL / "features").glob("*.sql"))),
          ("detect", sorted((SQL / "detect").glob("*.sql"))),
          ("ladder", [SQL / "response_ladder.sql"])]
# Raw tables the detections may read. ground_truth is deliberately absent: detection never sees labels.
SOURCES = ["users", "devices", "logins", "account_events", "payment_methods", "subscriptions",
           "transactions", "usage_events", "disputes", "disposable_domains", "plan_prices"]
CREATE = re.compile(r"CREATE OR REPLACE (TABLE|VIEW) (\w+) AS\s*\n", re.I)
GENERATED = "-- GENERATED by dbt/sync_from_sql.py from {src}. Edit the file in sql/, not this one.\n"


def statements(path: Path) -> list[str]:
    """Split a file into statements on lines that end with ';' (no statement here ends mid-line)."""
    out, current = [], []
    for line in path.read_text().splitlines():
        current.append(line)
        if line.rstrip().endswith(";") and not line.lstrip().startswith("--"):
            out.append("\n".join(current))
            current = []
    return out


def templated(code: str, models: set[str]) -> str:
    """Swap table names for ref()/source() on code lines; comments are left as written."""
    def swap(line: str) -> str:
        if line.lstrip().startswith("--"):
            return line
        def repl(m):
            name = m.group(0)
            if name in models:
                return "{{ ref('" + name + "') }}"
            return "{{ source('raw', '" + name + "') }}"
        names = sorted(models | set(SOURCES), key=len, reverse=True)
        pattern = r"(?<![\w.'])(" + "|".join(map(re.escape, names)) + r")(?![\w(])"
        # Only rewrite code, never text inside '...' string literals ('' is an escaped quote).
        parts = re.split(r"('(?:[^']|'')*')", line)
        return "".join(part if part.startswith("'") else re.sub(pattern, repl, part) for part in parts)
    return "\n".join(swap(l) for l in code.splitlines())


def build() -> dict[Path, str]:
    parsed = []
    for layer, files in STAGES:
        for f in files:
            for stmt in statements(f):
                m = CREATE.search(stmt)
                if not m:
                    raise ValueError(f"{f.name}: statement without CREATE OR REPLACE ... AS")
                header = stmt[:m.start()].strip()
                body = stmt[m.end():].rstrip().rstrip(";")
                parsed.append((layer, f, m.group(1).lower(), m.group(2), header, body))
    models = {name for *_, name, _, _ in parsed}

    files: dict[Path, str] = {}
    for layer, src, kind, name, header, body in parsed:
        text = GENERATED.format(src=src.relative_to(ROOT))
        text += "{{ config(materialized='" + kind + "') }}\n"
        if header:
            text += header + "\n"
        text += templated(body, models) + "\n"
        files[DBT / "models" / layer / f"{name}.sql"] = text

    macros = (SQL / "macros.sql").read_text()
    files[DBT / "macros" / "create_duckdb_macros.sql"] = (
        GENERATED.format(src="sql/macros.sql")
        + "{% macro create_duckdb_macros() %}\n" + macros.strip() + "\n{% endmacro %}\n")

    sources_yml = ["version: 2", "", "sources:", "  - name: raw", "    schema: main",
                   "    description: Synthetic warehouse tables written by the generators (ground_truth excluded).",
                   "    tables:"] + [f"      - name: {t}" for t in SOURCES]
    files[DBT / "models" / "sources.yml"] = GENERATED.format(src="dbt/sync_from_sql.py").replace("-- ", "# ") + \
        "\n".join(sources_yml) + "\n"
    return files


def main():
    check = "--check" in sys.argv
    files = build()
    model_dir = DBT / "models"
    existing = {p for p in model_dir.rglob("*.sql")} if model_dir.exists() else set()
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    orphans = [p for p in existing if p not in files]
    if check:
        if stale or orphans:
            print("dbt models are out of date; run: python dbt/sync_from_sql.py")
            for p in stale + orphans:
                print("  ", p.relative_to(ROOT))
            sys.exit(1)
        print("dbt models are in sync with sql/")
        return
    for p in orphans:
        p.unlink()
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    print(f"wrote {len(files)} files ({len(files) - 2} models)")


if __name__ == "__main__":
    main()
